def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def clean(o):
    if isinstance(o, dict):
        return {str(k): clean(v) for k, v in o.items()}
    if isinstance(o, (list, tuple)):
        return [clean(v) for v in o]
    if isinstance(o, (np.integer,)):
        return int(o)
    if isinstance(o, (np.floating, float)):
        return None if np.isnan(o) else float(o)
    if isinstance(o, (np.bool_,)):
        return bool(o)
    return o


def pct(x):
    return f"{100 * x:.1f}%"


def render(a: dict, tables: dict) -> str:
    cov, cl, clo, st = a["coverage"], a["closed_days"], a["long_closures"], a["store_attributes"]
    w, pr, ho, ou, se = a["windows"], a["promo"], a["holidays"], a["outliers"], a["seasonality"]
    rec = a["reconciliation"]
    L = []
    add = L.append
    add("# Data audit — Rossmann Store Sales\n")
    add("_Generated by `scripts/audit_data.py`; all numbers come from `evals/results/data_audit.json`. "
        "Source: Rossmann store data from the Kaggle competition `rossmann-store-sales`; raw data is not included in this repository._\n")
    add(f"**Scopes.** Structure and data-quality counts (sections 1-4, 8 and the holiday coverage counts in 7) use all {cov['rows']:,} rows. "
        f"Sales-based descriptives (sections 5, 6, 9, 10 and the sales contrasts in 7) use only rows before the TEST window "
        f"(dates up to {w['validation']['end']}), so nothing about test-window sales informs modelling choices.\n")

    add("## 0. Known at forecast time vs not\n")
    add("| Column | Known in advance? | Note |\n|---|---|---|")
    for r in [
        ("Store, StoreType, Assortment, CompetitionDistance, CompetitionOpenSince*, Promo2, Promo2Since*, PromoInterval",
         "Yes", "Store attributes (slowly changing; treated as static)"),
        ("Date, DayOfWeek", "Yes", "Calendar"),
        ("StateHoliday, SchoolHoliday", "Yes", "Published holiday calendars"),
        ("Promo", "Yes (assumed)", "Planned promotions are scheduled ahead; assumed available for the forecast horizon"),
        ("Open", "Partly", "Regular opening pattern is known; unplanned closures are not. Handling is decided at modelling time"),
        ("Sales", "No", "Target"),
        ("**Customers**", "**No**", "**Observed only together with Sales. Never a feature and never used to build features (enforced by tests).**"),
    ]:
        add(f"| {r[0]} | {r[1]} | {r[2]} |")
    add("")

    add("## 1. Row counts and reconciliation to source\n")
    rows = [(k, f"{v['source']:,}" if isinstance(v['source'], int) else v['source'],
             f"{v['processed']:,}" if isinstance(v['processed'], int) else v['processed'], "ok" if v["match"] else "MISMATCH")
            for k, v in rec["train"]["checks"].items() if k != "state_holiday_counts"]
    rows.append(("state_holiday_counts", str(rec["train"]["checks"]["state_holiday_counts"]["source"]),
                 str(rec["train"]["checks"]["state_holiday_counts"]["processed"]),
                 "ok" if rec["train"]["checks"]["state_holiday_counts"]["match"] else "MISMATCH"))
    add("train.csv: independent streaming pass over the raw file vs the Parquet used downstream.\n")
    add(A.md_table(pd.DataFrame(rows, columns=["metric", "raw train.csv", "processed parquet", "match"])))
    add(f"\n- Raw `train.csv` newline-based record count: {rec['train_csv_line_records']:,}; pandas read: {rec['train_pandas_rows']:,}.")
    add(f"- `store.csv`: {rec['store_csv_line_records']:,} records, {rec['store_pandas_rows']:,} rows after conversion; "
        f"{'match' if rec['store_match'] else 'MISMATCH'}.")
    add(f"- All reconciliation checks match: **{rec['all_match']}**.")
    add(f"- sha256 train.csv `{a['provenance']['train_csv_sha256']}`, store.csv `{a['provenance']['store_csv_sha256']}`.\n")

    add("## 2. Coverage and missing store-days\n")
    add(f"- Stores: **{cov['n_stores']:,}** in train (store.csv: {st['n_stores']:,}; in train not in store.csv: "
        f"{cov['stores_in_train_not_in_store_csv']}; in store.csv not in train: {cov['stores_in_store_csv_not_in_train']}).")
    add(f"- Date range: **{cov['date_min']} to {cov['date_max']}**, {cov['n_days']:,} calendar days.")
    add(f"- Expected store-days (stores x days): {cov['expected_store_days']:,}; rows: {cov['rows']:,}; duplicate (Store, Date) rows: {cov['duplicate_store_date_rows']}.")
    add(f"- **Missing store-days (no row): {cov['missing_store_days']:,}** ({pct(cov['missing_share'])} of the grid). "
        f"{cov['stores_with_any_missing_day']:,} stores have at least one missing day (max {cov['max_missing_days_in_one_store']} for one store); "
        f"{cov['stores_with_no_missing_day']:,} have none. Up to {cov['max_stores_missing_on_one_date']} stores are missing on a single date.")
    add(f"- DayOfWeek consistent with Date in every row: {cov['dayofweek_consistent_with_date']}.\n")
    mm = pd.DataFrame(sorted(cov["missing_by_month"].items()), columns=["month", "missing store-days"])
    add("Missing store-days by month (months with none omitted):\n")
    add(A.md_table(mm))
    add("")

    add("## 3. Closed days (Open = 0) and open days with zero sales\n")
    add(f"- Rows with Open = 0: **{cl['open_zero_rows']:,}** ({pct(cl['open_zero_share_of_rows'])} of rows); "
        f"their total Sales = {cl['open_zero_sales_sum']:,}; rows among them with Sales > 0: {cl['open_zero_rows_with_positive_sales']:,}.")
    add(f"- Of those closed rows, on a state-holiday: {cl['open_zero_on_state_holiday_rows']:,}; on a school-holiday: {cl['open_zero_on_school_holiday_rows']:,}.")
    add(f"- Closed rows by DayOfWeek (1 = Monday): {cl['open_zero_by_dayofweek']}.")
    add(f"- **Open days with zero sales: {cl['open_rows_with_zero_sales']:,}** "
        f"({100 * cl['open_rows_with_zero_sales_share_of_open']:.4f}% of {cl['open_rows']:,} open rows), across {cl['open_rows_with_zero_sales_n_stores']:,} stores; "
        f"by year: {cl['open_rows_with_zero_sales_by_year']}. Customers on those rows sum to {cl['open_rows_with_zero_sales_customers_sum']:,}.\n")

    add(f"## 4. Long closures (>= {clo['min_run_days']} consecutive days with no row or Open = 0)\n")
    add(f"- Runs: **{clo['n_runs']:,}** across **{clo['n_stores']:,}** stores"
        + (f"; longest {clo['longest_run_days']} days; runs made only of missing rows: {clo['runs_that_are_entirely_missing_rows']:,}, "
           f"only of Open = 0 rows: {clo['runs_that_are_entirely_closed_rows']:,}, the rest mix both (e.g. a missing block followed by a holiday closure); runs touching the start of the data: {clo['runs_touching_data_start']}, "
           f"touching the end: {clo['runs_touching_data_end']}." if clo["n_runs"] else "."))
    if clo["n_runs"]:
        add("\nMost common (start, end) clusters:\n")
        add(A.md_table(pd.DataFrame(clo["top_clusters_same_start_end"])))
        add("\nRuns by start month: " + str(clo["by_start_year_month"]))
        add("\nFull list: `evals/results/audit_long_closures.csv`.")
    add("")

    sd = a["sales_distribution"]
    o = sd["overall_open_positive"]
    add("## 5. Sales distribution (open days with Sales > 0)\n")
    add(f"Overall: n = {o['n']:,}, mean {o['mean']:,.0f}, std {o['std']:,.0f}, median {o['p50']:,.0f}, p5 {o['p5']:,.0f}, p95 {o['p95']:,.0f}, min {o['min']:,.0f}, max {o['max']:,.0f}.\n")
    for key, title in [("DayOfWeek", "Day of week (1 = Monday)"), ("StoreType", "Store type"), ("Assortment", "Assortment")]:
        add(f"**By {title}**\n")
        add(A.md_table(tables[key].round(3), "{:,.2f}"))
        add("")

    add("## 6. Promotions (naive descriptive, not an effect)\n")
    add(f"- Share of rows with Promo = 1: **{pct(pr['promo_share_all_rows'])}** (of open rows: {pct(pr['promo_share_open_rows'])}) [pre-test scope].")
    add(f"- Promo share by DayOfWeek: { {k: round(v, 3) for k, v in pr['promo_share_by_dayofweek'].items()} }.")
    add(f"- Mean Sales on open positive days: promo {pr['mean_sales_promo']:,.0f} vs non-promo {pr['mean_sales_no_promo']:,.0f} "
        f"(ratio {pr['ratio_of_means']:.3f}); medians {pr['median_sales_promo']:,.0f} vs {pr['median_sales_no_promo']:,.0f}.")
    add(f"- Promo timing: autocorrelation of the daily Mon-Fri promo share {pr['weekday_promo_share_autocorrelation']}; "
        f"a store's Promo flag on a Monday differs from its previous Monday in {pct(pr['monday_promo_flip_rate_vs_previous_monday'])} of "
        f"{pr['monday_pairs_compared']:,} consecutive-Monday pairs.")
    add("- **This is a naive descriptive contrast.** Promo days are not randomly assigned: they differ in weekday mix, store mix and season, "
        "so the gap must not be read as a promotion effect. The per-weekday split below shows how the mix matters.\n")
    add(A.md_table(pd.DataFrame(pr["by_dayofweek"]).round(1)))
    add("")

    add("## 7. School and state holidays\n")
    add(f"- SchoolHoliday = 1 on {pct(ho['school_holiday_share_all_rows'])} of rows (by year: "
        f"{ {k: round(v, 3) for k, v in ho['school_holiday_share_by_year'].items()} }); {ho['dates_with_any_school_holiday_store']:,} distinct dates have at least one store flagged.")
    add(f"- StateHoliday rows by code (0 = none, a = public, b = Easter, c = Christmas): {ho['state_holiday_rows']}; distinct dates a/b/c: {ho['state_holiday_distinct_dates']}.")
    add(f"- Share of rows with Open = 1 by code: { {k: round(v, 3) for k, v in ho['state_holiday_open_share'].items()} }.")
    add(f"- Naive mean Sales on open positive days by state-holiday code [pre-test]: { {k: round(v) for k, v in ho['naive_mean_sales_open_positive_by_state_holiday'].items()} }; "
        f"by SchoolHoliday: { {k: round(v) for k, v in ho['naive_mean_sales_open_positive_school_holiday'].items()} } (naive descriptive, not an effect).\n")

    add("## 8. Store attributes\n")
    add(f"- Stores with missing CompetitionDistance: **{st['competition_distance_missing']}**; missing CompetitionOpenSinceMonth/Year: "
        f"{st['competition_open_since_month_missing']}/{st['competition_open_since_year_missing']}.")
    add(f"- **Promo2 stores: {st['promo2_stores']}** of {st['n_stores']:,}; of those missing Promo2Since week/year: {st['promo2_stores_missing_since_week_or_year']}; "
        f"non-Promo2 stores with a PromoInterval: {st['non_promo2_stores_with_promo_interval']}.")
    add(f"- StoreType counts: {st['store_type_counts']}; Assortment counts: {st['assortment_counts']}; PromoInterval counts: {st['promo_interval_counts']}.")
    cd = st["competition_distance"]
    add(f"- CompetitionDistance (m): median {cd['p50']:,.0f}, p5 {cd['p5']:,.0f}, p95 {cd['p95']:,.0f}, max {cd['max']:,.0f}.\n")

    add("## 9. Outliers (open days with Sales > 0) [pre-test scope]\n")
    add(f"- Global IQR: Q1 {ou['global_q1']:,.0f}, Q3 {ou['global_q3']:,.0f}; days above Q3 + 1.5 IQR ({ou['upper_fence_1.5iqr']:,.0f}): "
        f"{ou['n_above_1.5iqr_fence']:,}; above Q3 + 3 IQR ({ou['upper_fence_3iqr']:,.0f}): {ou['n_above_3iqr_fence']:,}. p99 {ou['p99']:,.0f}, p99.9 {ou['p999']:,.0f}.")
    add(f"- Maximum single-day sales {ou['max_sales']:,} (store {ou['max_sales_store']}, {ou['max_sales_date']}).")
    add(f"- Per-store robust z ({ou['robust_z_definition']}) beyond +/-{ou['per_store_robust_z_threshold']:.0f}: "
        f"{ou['n_robust_z_high']:,} high days in {ou['stores_with_robust_z_high']:,} stores; {ou['n_robust_z_low']:,} low days in {ou['stores_with_robust_z_low']:,} stores.")
    add("- No values have been removed or capped; this section only describes them.\n")

    add("## 10. Seasonality [pre-test scope]\n")
    add(f"Index = {se['index_definition']}; 1.0 is a store's own average.\n")
    add("**Weekly pattern**\n")
    add(A.md_table(tables["dow"].round(3)))
    add("\n**Yearly pattern, by month** (months Jul-Dec have fewer years of data than Jan-Jun, see `n_years`)\n")
    add(A.md_table(tables["month"].round(3)))
    add(f"\nISO week with lowest index: {se['week_of_year_index_min']}; highest: {se['week_of_year_index_max']} (full profile: `evals/results/audit_week_of_year.csv`, by-year view: `audit_year_month_index.csv`).")
    add(f"\nAutocorrelation of the daily mean store index (n = {se['daily_series_days']:,} days; {se['daily_series_days_excluded_sparse_open']} excluded because fewer than half of the stores were open, not interpolated): {se['daily_mean_index_autocorrelation']}. Compare the weekly lag with the promo-share autocorrelation in section 6: weekly lags are affected by how Promo is scheduled.\n")
    return "\n".join(L) + "\n"


def main():
    config.RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    mg = MemGuard(config.RESULTS_DIR / "audit_data_mem.log")
    mg.start_watchdog()
    mg.stage("start")
    if not config.PROCESSED_TRAIN.exists():
        sys.exit("run scripts/prepare_data.py first")
    train, store = load_processed()
    mg.stage("loaded parquet")

    w = make_windows()
    test_start = w["test"][0]
    pre = train[train["Date"] < test_start]

    src = A.source_stats_from_csv(config.RAW_TRAIN)
    mg.stage("streamed raw csv")
    rec_train = A.reconcile(src, A.frame_stats(train))
    store_line_records = A.count_data_lines(config.RAW_STORE)
    reconciliation = {
        "train": rec_train, "train_csv_line_records": A.count_data_lines(config.RAW_TRAIN),
        "train_pandas_rows": int(len(train)), "store_csv_line_records": store_line_records,
        "store_pandas_rows": int(len(store)), "store_match": store_line_records == len(store),
    }
    reconciliation["all_match"] = bool(rec_train["all_match"] and reconciliation["store_match"]
                                       and reconciliation["train_csv_line_records"] == len(train))

    sales_dist, tables = A.sales_distribution(pre, store)
    seas, seas_tables = A.seasonality(pre)
    tables.update(seas_tables)
    clo = A.long_closures(train, config.LONG_CLOSURE_DAYS)
    mg.stage("computed audit")

    audit = {
        "provenance": {"raw_dir": "$ROSSMANN_RAW_DIR", "train_csv_sha256": sha256(config.RAW_TRAIN),
                       "store_csv_sha256": sha256(config.RAW_STORE), "python": platform.python_version(),
                       "pandas": pd.__version__, "numpy": np.__version__,
                       "sales_scope": f"rows with Date < {test_start.date()} (before TEST window)",
                       "peak_rss_mb": mg.peak_mb()},
        "windows": {k: {"start": str(a.date()), "end": str(b.date())} for k, (a, b) in w.items()},
        "reconciliation": reconciliation,
        "coverage": A.coverage(train, store),
        "closed_days": A.closed_days(train),
        "long_closures": clo,
        "sales_distribution": sales_dist,
        "promo": A.promo_summary(pre),
        "holidays": A.holiday_summary(pre, train),
        "store_attributes": A.store_attributes(store),
        "outliers": A.outliers(pre),
        "seasonality": seas,
        "known_in_advance": {"yes": ["Store attributes", "Date/DayOfWeek", "StateHoliday", "SchoolHoliday", "Promo (planned, assumed)"],
                             "partly": ["Open"], "no": ["Sales (target)", "Customers"]},
    }
    audit = clean(audit)
    (config.RESULTS_DIR / "data_audit.json").write_text(json.dumps(audit, indent=2) + "\n")

    csv_map = {"DayOfWeek": "audit_dow.csv", "StoreType": "audit_store_type.csv", "Assortment": "audit_assortment.csv",
               "dow": "audit_dow_index.csv", "month": "audit_month_index.csv",
               "year_month_index": "audit_year_month_index.csv", "week_of_year": "audit_week_of_year.csv"}
    for k, fn in csv_map.items():
        tables[k].to_csv(config.RESULTS_DIR / fn, index=False)
    pd.DataFrame(clo["runs"]).to_csv(config.RESULTS_DIR / "audit_long_closures.csv", index=False)

    config.DOCS_DIR.mkdir(exist_ok=True)
    (config.DOCS_DIR / "data_audit.md").write_text(render(audit, tables))
    mg.stage("written")
    print("reconciliation all_match:", reconciliation["all_match"])


if __name__ == "__main__":
    main()
