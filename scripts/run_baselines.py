def log_rows(rows):
    new = not SPEC_LOG.exists()
    with open(SPEC_LOG, "a", newline="") as f:
        w = csv.DictWriter(f, fieldnames=LOG_FIELDS)
        if new:
            w.writeheader()
        for r in rows:
            w.writerow({k: r.get(k, "") for k in LOG_FIELDS})


def fmt(x):
    return "" if x is None or (isinstance(x, float) and np.isnan(x)) else f"{x:.6g}"


def run_config(factory, frame, store, splits, run_id, stage, family, params):
    """Run one configuration split by split, logging each split. Returns (preds, diags, total seconds)."""
    fc = factory()
    preds, diags, total = [], [], 0.0
    for sp in splits:
        t0 = time.time()
        p, d = run_splits(fc, frame, store, [sp])
        dt = time.time() - t0
        total += dt
        m = fold_metrics(p).iloc[0]
        log_rows([{"run_id": run_id, "stage": stage, "baseline": family, "params": json.dumps(params),
                   "split": sp.fold, "n_rows": int(m["n"]), **{k: fmt(m[k]) for k in METRICS},
                   "runtime_s": f"{dt:.1f}",
                   "status": {"backtest": "tried", "backtest-probe": "probe", "validation": "validation"}[stage]}])
        preds.append(p)
        diags.extend(d)
    return pd.concat(preds, ignore_index=True), diags, total


def cell(c, nd=3):
    if c["value"] is None:  # empty group (NaN in the results)
        return "n/a"
    return f"{c['value']:.{nd}f} [{c['lo']:.{nd}f}, {c['hi']:.{nd}f}]"


def render(out, stage_title, views_labels):
    L, add = [], None
    add = L.append
    names = list(out["baselines"])
    lab = {n: f"{LABEL[n]} ({', '.join(f'{k}={v}' for k, v in out['baselines'][n]['params'].items())})" for n in names}
    add(f"# {stage_title}\n")
    add(f"_Generated by `scripts/run_baselines.py` (run `{out['run_id']}`). Protocol: `docs/forecast_protocol.md`. "
        f"All numbers come from `{out['json_name']}`; CIs are 95% store-clustered bootstrap intervals "
        f"({out['bootstrap']['n_boot']} resamples, seed {out['bootstrap']['seed']}), shown as value [lo, hi]._\n")
    add("Metrics on open days with Sales > 0: RMSPE, WAPE = sum|e|/sum y, MASE vs in-sample seasonal naive (period 7), "
        "bias = sum(e)/sum(y) with e = forecast - actual (positive = over-forecast). 'Mean over folds' = unweighted mean "
        "of per-fold metrics. Open = 0 days are forecast as 0 and excluded; missing store-days are not evaluated.\n")
    if out.get("selection"):
        add("## Configuration selection (backtest folds only, criterion: mean-over-folds WAPE)\n")
        add("| Baseline | Config | Mean WAPE | Mean RMSPE | Status |\n|---|---|---|---|---|")
        for fam, s in out["selection"].items():
            for c in s["configs"]:
                add(f"| {LABEL[fam]} | {c['params']} | {c['mean_wape']:.4f} | {c['mean_rmspe']:.4f} | {c['status']} |")
        for fam, why in out.get("skipped", {}).items():
            add(f"| {LABEL[fam]} | - | - | - | skipped: {why} |")
        add("\nTuned baselines are tuned and scored on the same folds, so their backtest numbers are mildly optimistic.\n")
    first_view = list(views_labels)[0]
    add(f"## Overall ({views_labels[first_view]})\n")
    add("| Baseline | RMSPE | WAPE | MASE | Bias |\n|---|---|---|---|---|")
    for n in names:
        v = out["baselines"][n]["results"]["overall"]["views"][first_view]
        add(f"| {lab[n]} | " + " | ".join(cell(v[m], 4 if m != "mase" else 3) for m in METRICS) + " |")
    add("")
    for m in METRICS:
        folds = list(out["baselines"][names[0]]["results"]["overall"]["per_fold"])
        if len(folds) == 1:
            continue  # single window: already shown in the overall table
        add(f"### {m.upper()} by fold\n")
        add("| Fold | " + " | ".join(lab[n] for n in names) + " |\n|---|" + "---|" * len(names))
        for f in folds:
            add(f"| {f} | " + " | ".join(cell(out["baselines"][n]["results"]["overall"]["per_fold"][f][m]) for n in names) + " |")
        for v, vl in views_labels.items():
            add(f"| **{vl}** | " + " | ".join(cell(out["baselines"][n]["results"]["overall"]["views"][v][m]) for n in names) + " |")
        add("")
    for key, title in [("horizon", "Horizon (days after cutoff)"), ("store_type", "Store type"),
                       ("promo", "Promo vs non-promo target day"), ("dow", "Day of week (1 = Monday)"),
                       ("history", "History: stale = no open day with sales in the 56 days before the cutoff (pre-registered)"),
                       ("row_coverage", "Row coverage (POST-HOC diagnostic): sparse = fewer than 100 rows in the 200 days before the cutoff")]:
        add(f"## By {title} ({views_labels[first_view]})\n")
        groups = out["baselines"][names[0]]["results"][key]["groups"]
        for m in METRICS:
            add(f"**{m.upper()}**\n")
            add("| Group | rows | " + " | ".join(lab[n] for n in names) + " |\n|---|---|" + "---|" * len(names))
            for g in groups:
                nrows = out["baselines"][names[0]]["results"][key]["views"][first_view][g]["n_rows"]
                add(f"| {g} | {nrows:,} | " + " | ".join(
                    cell(out["baselines"][n]["results"][key]["views"][first_view][g][m]) for n in names) + " |")
            add("")
    add("## Fold-to-fold spread (point estimates; the bootstrap CIs above only capture store sampling)\n")
    add("| Baseline | WAPE min - max across folds | WAPE std across folds | RMSPE min - max |\n|---|---|---|---|")
    for n in names:
        pf = out["baselines"][n]["results"]["overall"]["per_fold"]
        w, r = [pf[f]["wape"]["value"] for f in pf], [pf[f]["rmspe"]["value"] for f in pf]
        add(f"| {lab[n]} | {min(w):.3f} - {max(w):.3f} | {np.std(w, ddof=1) if len(w) > 1 else float('nan'):.3f} | {min(r):.3f} - {max(r):.3f} |")
    add("\n## RMSPE concentration: share of the summed squared percentage error from the worst 0.1% of rows, by fold\n")
    add("| Baseline | " + " | ".join(f"fold {f}" for f in out["baselines"][names[0]]["error_concentration"]) + " |\n|---|" + "---|" * len(out["baselines"][names[0]]["error_concentration"]))
    for n in names:
        add(f"| {lab[n]} | " + " | ".join(f"{v['share_of_sq_pct_error']:.2f} (min y {v['min_actual_in_top_k']:,.0f})"
                                         for v in out["baselines"][n]["error_concentration"].values()) + " |")
    add("")
    add("## Best baseline\n")
    b = out["comparison"]
    add(f"- Lowest mean-over-folds WAPE: **{lab[b['best_by_wape']]}**; lowest RMSPE: **{lab[b['best_by_rmspe']]}**; "
        f"lowest MASE: **{lab[b['best_by_mase']]}**.")
    add(f"- Wins per fold (lowest WAPE): {b['wins_per_fold_wape']}; (lowest RMSPE): {b['wins_per_fold_rmspe']}.")
    if b.get("paired_vs_runner_up"):
        pr = b["paired_vs_runner_up"]
        add(f"- Paired difference, {lab[pr['a']]} minus {lab[pr['b']]} (negative = first is better, paired bootstrap over the "
            "same store resamples):")
        for m in METRICS:
            d = pr["metrics"][m]
            add(f"  - {m.upper()}: {d['diff']:+.4f} [{d['lo']:+.4f}, {d['hi']:+.4f}]")
    if b.get("paired_vs_backtest_best"):
        pr = b["paired_vs_backtest_best"]
        add(f"- Paired differences vs the backtest-best baseline ({lab[pr['reference']]}), WAPE (baseline minus reference):")
        for n, d in pr["wape"].items():
            add(f"  - {lab[n]}: {d['diff']:+.4f} [{d['lo']:+.4f}, {d['hi']:+.4f}]")
    add("\nLowest-WAPE baseline per group (point estimates; compare against the CIs above before reading much into small gaps):\n")
    add("| Breakdown | Group | Best by WAPE |\n|---|---|---|")
    for key, groups in b["best_by_group_wape"].items():
        for g, n in groups.items():
            add(f"| {key} | {g} | {lab.get(n, n)} |")
    add("\n## Forecast sources (share of forecasts by rule, all evaluated splits)\n")
    add("| Baseline | counts by rule |\n|---|---|")
    for n in names:
        add(f"| {lab[n]} | {out['baselines'][n]['fallback_counts']} |")
    add("\n## Run info\n")
    add(f"- Runtime: {out['runtime_s']:.0f} s; peak RSS of the main process: {out['peak_rss_mb']} MB "
        f"(ETS worker processes not included; at most {config.MAX_WORKERS} workers).")
    return "\n".join(L) + "\n"


def best_by_group(out, view):
    """Lowest-WAPE baseline per breakdown group; groups with no evaluated rows are reported as n/a."""
    names = list(out["baselines"])
    res = {}
    for key in BREAKDOWNS:
        gs = out["baselines"][names[0]]["results"][key]["groups"]
        res[key] = {}
        for g in gs:
            vals = {n: out["baselines"][n]["results"][key]["views"][view][g]["wape"]["value"] for n in names}
            vals = {n: v for n, v in vals.items() if v is not None and not np.isnan(v)}
            res[key][g] = min(vals, key=vals.get) if vals else "n/a"
    return res


def compare(out, boot_views, view, backtest_best=None):
    names = list(out["baselines"])
    val = {m: {n: out["baselines"][n]["results"]["overall"]["views"][view][m]["value"] for n in names} for m in METRICS}
    best = {m: min(names, key=lambda n: val[m][n]) for m in ("rmspe", "wape", "mase")}
    folds = list(out["baselines"][names[0]]["results"]["overall"]["per_fold"])
    wins = {m: {} for m in ("wape", "rmspe")}
    for m in wins:
        for f in folds:
            w = min(names, key=lambda n: out["baselines"][n]["results"]["overall"]["per_fold"][f][m]["value"])
            wins[m][w] = wins[m].get(w, 0) + 1
    by_group = best_by_group(out, view)
    cmp_ = {"best_by_rmspe": best["rmspe"], "best_by_wape": best["wape"], "best_by_mase": best["mase"],
            "wins_per_fold_wape": wins["wape"], "wins_per_fold_rmspe": wins["rmspe"], "best_by_group_wape": by_group}
    order = sorted(names, key=lambda n: val["wape"][n])
    if len(order) > 1:
        a, b = order[0], order[1]
        cmp_["paired_vs_runner_up"] = {"a": a, "b": b, "metrics": {
            m: paired_difference(boot_views[a][view][:, 0, METRICS.index(m)], boot_views[b][view][:, 0, METRICS.index(m)],
                                 val[m][a], val[m][b]) for m in METRICS}}
    if backtest_best and backtest_best in names:
        j = METRICS.index("wape")
        cmp_["paired_vs_backtest_best"] = {"reference": backtest_best, "wape": {
            n: paired_difference(boot_views[n][view][:, 0, j], boot_views[backtest_best][view][:, 0, j],
                                 val["wape"][n], val["wape"][backtest_best]) for n in names if n != backtest_best}}
    return cmp_


def clean(o):
    if isinstance(o, dict):
        return {str(k): clean(v) for k, v in o.items()}
    if isinstance(o, (list, tuple)):
        return [clean(v) for v in o]
    if isinstance(o, np.generic):
        o = o.item()
    if isinstance(o, float) and np.isnan(o):
        return None
    return o


TITLES = {"backtest": "Baselines — rolling-origin backtest (8 folds inside TRAIN)",
          "validation": "Baselines — VALIDATION confirmation (single run, no tuning)"}
VIEW_LABELS = {
    "backtest": {"all_folds": "mean over all 8 folds", "folds_2_5": "mean over folds 2-5 (Jul-Dec 2014 gap period)",
                 "other_folds": "mean over folds 1, 6, 7, 8"},
    "validation": {"validation": "VALIDATION window 2015-05-09..2015-06-19, forecast from cutoff 2015-05-08"}}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--stage", choices=["backtest", "validation"], required=True)
    ap.add_argument("--render-only", action="store_true", help="re-render the .md from the saved .json, no recomputation")
    args = ap.parse_args()
    stage = args.stage
    if args.render_only:
        out = json.loads((RES / f"baselines_{stage}.json").read_text())
        # derived field only: recompute from the saved results (no model is re-run)
        out["comparison"]["best_by_group_wape"] = best_by_group(out, list(VIEW_LABELS[stage])[0])
        (RES / f"baselines_{stage}.json").write_text(json.dumps(out, indent=2) + "\n")
        (RES / f"baselines_{stage}.md").write_text(render(out, TITLES[stage], VIEW_LABELS[stage]))
        return
    t_start = time.time()
    RES.mkdir(parents=True, exist_ok=True)
    mg = MemGuard(RES / f"baselines_{stage}_mem.log")
    mg.start_watchdog()
    run_id = datetime.now().strftime("%Y%m%dT%H%M%S")
    frame = load_modelling_frame()
    _, store = load_processed()
    assert frame["Date"].max() < pd.Timestamp("2015-06-20"), "TEST rows must not be loaded"
    mg.stage(f"{stage}: frame loaded ({frame['Date'].max().date()} is the last date)")
    store_ids = sorted(store["Store"].unique().tolist())
    boot = StoreBootstrap(len(store_ids))
    out = {"run_id": run_id, "stage": stage, "bootstrap": {"n_boot": N_BOOT, "seed": SEED, "clustered_by": "Store"},
           "json_name": f"baselines_{stage}.json", "baselines": {}}

    if stage == "backtest":
        splits, views = backtest_splits(), BACKTEST_VIEWS
        fold_ids = [s.fold for s in splits]
        views_labels = {"all_folds": "mean over all 8 folds", "folds_2_5": "mean over folds 2-5 (Jul-Dec 2014 gap period)",
                        "other_folds": "mean over folds 1, 6, 7, 8"}
        selection, skipped, chosen_preds, chosen_diags, chosen_params = {}, {}, {}, {}, {}
        for fam, configs in FAMILIES.items():
            tried = []
            for params, factory in configs:
                if fam == "ets_additive_seasonal" and params == configs[0][0]:
                    # protocol: skip the whole grid when the projected backtest time exceeds the budget
                    t0 = time.time()
                    p1, d1, _ = run_config(factory, frame, store, splits[:1], run_id, "backtest-probe", fam, params)
                    per_fold = time.time() - t0
                    projected = per_fold * len(splits) * len(configs)
                    mg.stage(f"ETS probe: {per_fold:.0f}s per fold, projected grid {projected:.0f}s")
                    if projected > ETS_BUDGET_S:
                        skipped[fam] = f"projected {projected:.0f}s > {ETS_BUDGET_S}s budget (measured {per_fold:.0f}s per fold)"
                        log_rows([{"run_id": run_id, "stage": "backtest", "baseline": fam, "params": json.dumps(params),
                                   "split": "all", "status": "skipped", "note": skipped[fam]}])
                        break
                preds, diags, secs = run_config(factory, frame, store, splits, run_id, "backtest", fam, params)
                fm = fold_metrics(preds)
                tried.append({"params": params, "mean_wape": float(fm["wape"].mean()), "mean_rmspe": float(fm["rmspe"].mean()),
                              "mean_mase": float(fm["mase"].mean()), "mean_bias": float(fm["bias"].mean()),
                              "preds": preds, "diags": diags, "secs": secs})
                mg.stage(f"{fam} {params} mean WAPE {tried[-1]['mean_wape']:.4f} ({secs:.0f}s)")
            if not tried:
                continue
            best = min(tried, key=lambda t: t["mean_wape"])
            selection[fam] = {"criterion": "mean-over-folds WAPE", "configs": []}
            for t in tried:
                status = "selected" if t is best else "dropped"
                selection[fam]["configs"].append({"params": t["params"], "mean_wape": t["mean_wape"],
                                                  "mean_rmspe": t["mean_rmspe"], "status": status})
                log_rows([{"run_id": run_id, "stage": "backtest", "baseline": fam, "params": json.dumps(t["params"]),
                           "split": "mean_over_8_folds", "n_rows": len(t["preds"]), "rmspe": fmt(t["mean_rmspe"]),
                           "wape": fmt(t["mean_wape"]), "mase": fmt(t["mean_mase"]), "bias": fmt(t["mean_bias"]),
                           "runtime_s": f"{t['secs']:.1f}", "status": status,
                           "note": "selected on mean WAPE over the 8 backtest folds" if status == "selected" else
                                   "not best on mean WAPE; dropped"}])
            chosen_preds[fam], chosen_diags[fam], chosen_params[fam] = best["preds"], best["diags"], best["params"]
        out["selection"], out["skipped"] = selection, skipped
        (RES / "baselines_selected.json").write_text(json.dumps(
            {"run_id": run_id, "selected": chosen_params, "skipped": skipped}, indent=2) + "\n")
    else:
        sel = json.loads((RES / "baselines_selected.json").read_text())
        splits = [validation_split()]
        fold_ids, views = ["validation"], {"validation": ["validation"]}
        views_labels = {"validation": "VALIDATION window 2015-05-09..2015-06-19, forecast from cutoff 2015-05-08"}
        chosen_preds, chosen_diags, chosen_params = {}, {}, sel["selected"]
        out["selected_from_backtest_run"] = sel["run_id"]
        for fam, params in sel["selected"].items():
            factory = next(f for p, f in FAMILIES[fam] if p == params)
            chosen_preds[fam], chosen_diags[fam], _ = run_config(factory, frame, store, splits, run_id, "validation", fam, params)
            mg.stage(f"validation {fam} {params}")

    boot_views = {}
    for fam, preds in chosen_preds.items():
        res, bv = evaluate(preds, store_ids, fold_ids, boot, views)
        out["baselines"][fam] = {"params": chosen_params[fam], "results": res,
                                 "diagnostics": chosen_diags[fam], "error_concentration": error_concentration(preds), "fallback_counts": fallback_summary(chosen_diags[fam])}
        boot_views[fam] = bv
        preds.to_parquet(config.PROCESSED_DIR / f"preds_{stage}_{fam}.parquet", index=False)  # untracked
    first_view = list(views)[0]
    ref = None
    if stage == "validation":
        bt = json.loads((RES / "baselines_backtest.json").read_text())
        ref = bt["comparison"]["best_by_wape"]
    out["comparison"] = compare(out, boot_views, first_view, ref)
    if stage == "validation":
        out["comparison"]["backtest_best_by_wape"] = ref
    out["runtime_s"] = time.time() - t_start
    out["peak_rss_mb"] = mg.peak_mb()
    out["protocol"] = "docs/forecast_protocol.md"
    out = clean(out)
    (RES / f"baselines_{stage}.json").write_text(json.dumps(out, indent=2) + "\n")
    title = "Baselines — rolling-origin backtest (8 folds inside TRAIN)" if stage == "backtest" else \
        "Baselines — VALIDATION confirmation (single run, no tuning)"
    (RES / f"baselines_{stage}.md").write_text(render(out, title, views_labels))
    mg.stage(f"{stage}: done in {out['runtime_s']:.0f}s")
    print(json.dumps(out["comparison"], indent=1)[:3000])


if __name__ == "__main__":
    main()
