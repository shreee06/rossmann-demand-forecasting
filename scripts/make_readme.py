"""Generate README.md from evals/results/*.json. tests/test_readme.py fails if README.md drifts from this output.

  python scripts/make_readme.py          # write README.md
  python scripts/make_readme.py --check  # exit 1 if README.md differs
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "evals" / "results"
M = ["rmspe", "wape", "mase", "bias"]
SCREENSHOTS = [
    ("app_comparison.png", "Comparison tab: TEST, VALIDATION and backtest metrics with 95% CIs."),
    ("app_error_by_horizon.png", "Error by horizon: WAPE per 7-day bucket on TEST and in the backtest."),
    ("app_promo_and_store_type.png", "Promo vs non-promo days and store types on TEST (forecast error, not promotion effects)."),
    ("app_intervals.png", "Interval coverage and width, uncalibrated and calibrated, across backtest, VALIDATION and TEST."),
    ("app_limitations.png", "Limitations panel shown in the app."),
]


def j(name):
    return json.loads((RES / name).read_text())


def ci(c, nd=3):
    return f"{c['value']:.{nd}f} [{c['lo']:.{nd}f}, {c['hi']:.{nd}f}]"


def diff(d, nd=4):
    return f"{d['diff']:+.{nd}f} [{d['lo']:+.{nd}f}, {d['hi']:+.{nd}f}]"


def pct(x):
    return f"{100 * x:.1f}%"


def render() -> str:
    audit, win = j("data_audit.json"), j("windows.json")
    bb, bv = j("baselines_backtest.json"), j("baselines_validation.json")
    mb, mv, ft = j("model_backtest.json"), j("model_validation.json"), j("final_test.json")
    ivc, ivb, promo = j("intervals_calibrated.json"), j("intervals.json"), j("promo_analysis.json")
    grid, rec = j("model_grid_selection.json"), j("test_run_record.json")
    cov, cl = audit["coverage"], audit["closed_days"]
    W = win["windows"]
    L = []
    add = L.append

    add("# Retail demand forecasting — Rossmann Store Sales\n")
    add("Forecast daily sales of 1,115 Rossmann drugstores 42 days ahead, with a pre-registered evaluation protocol, honest baselines, "
        "a global LightGBM model, calibrated prediction intervals and a promotion analysis that is explicitly an association.\n")
    add("_This README is generated by `scripts/make_readme.py` from `evals/results/*.json`; `tests/test_readme.py` fails if any number here "
        "differs from the result files._\n")
    add("![TEST comparison](docs/images/test_comparison.png)\n")

    add("## Problem\n")
    add(f"At a cutoff date, forecast `Sales` for every store for each of the next 42 days using only data up to the cutoff plus information known "
        f"in advance (calendar, state/school holidays, planned `Promo`, store attributes). Days with `Open = 0` are forecast as 0 and excluded "
        f"from the metrics; evaluated rows are open days with `Sales > 0`.\n")

    add("## Data\n")
    add("- Source: Rossmann store data from the Kaggle competition "
        "[`rossmann-store-sales`](https://www.kaggle.com/competitions/rossmann-store-sales). Credit to Rossmann and Kaggle.")
    add("- **The data is not included in this repository** and must not be redistributed. To reproduce: accept the competition rules on Kaggle, "
        "download `train.csv` and `store.csv` (e.g. `kaggle competitions download -c rossmann-store-sales`), and set `ROSSMANN_RAW_DIR` to that folder. "
        "`test.csv` has no sales and is not used.")
    add(f"- {cov['rows']:,} store-day rows, {cov['n_stores']:,} stores, {cov['date_min']} to {cov['date_max']} ({cov['n_days']} days). "
        f"{cov['missing_store_days']:,} store-days have no row ({pct(cov['missing_share'])}); up to {cov['max_stores_missing_on_one_date']} stores "
        f"are missing at the same time in July-December 2014. {cl['open_zero_rows']:,} rows are closed days. Full audit: "
        "[`docs/data_audit.md`](docs/data_audit.md).\n")

    add("## Protocol and leakage rules\n")
    add("Each step's protocol was committed before the corresponding runs: [`docs/forecast_protocol.md`](docs/forecast_protocol.md) (baselines), "
        "[`docs/model_protocol.md`](docs/model_protocol.md) (model), [`docs/final_protocol.md`](docs/final_protocol.md) (TEST). Deviations are dated amendments.\n")
    add(f"- Windows: TRAIN {W['train']['start']}..{W['train']['end']}, VALIDATION {W['validation']['start']}..{W['validation']['end']}, "
        f"TEST {W['test']['start']}..{W['test']['end']}. 8 rolling-origin backtest folds (42-day horizons) inside TRAIN; all tuning and selection "
        "used the backtest folds only; VALIDATION was used once per step for confirmation; TEST was evaluated once "
        f"(run record: commit `{rec['git_commit'][:7]}`, {rec['n_evaluated_rows']:,} rows, refuses a second run).")
    add("- **`Customers` is never used**: it is observed only together with sales, so it is unknown at forecast time. Modelling code reads explicit "
        "column lists without it, and tests fail if any module, feature list or script uses it.")
    add("- Every feature is computed from data up to its cutoff plus calendar/holiday/promo information up to the end of the horizon "
        "(tests move the cutoff and perturb future data to check this).")
    add("- Metrics on evaluated rows: RMSPE (competition metric), WAPE = Σ|e|/Σy, MASE vs in-sample seasonal naive (7), Bias = Σ(forecast−actual)/Σy. "
        "95% CIs: store-clustered bootstrap (500 resamples); differences are paired. CIs reflect store sampling, not period-to-period variation.")
    add("- Every configuration tried, including dropped ones, is in `evals/results/spec_log.csv`.\n")

    add("## Baselines (backtest: mean over 8 folds)\n")
    add("| Baseline | Config | RMSPE | WAPE | MASE | Bias | VALIDATION WAPE |\n|---|---|---|---|---|---|---|")
    names = {"seasonal_naive_7": "Seasonal naive 7", "seasonal_naive_14": "Seasonal naive 14", "promo_weekday_mean": "Promo-aware weekday mean",
             "store_median_x_index": "Store median × weekday/promo index", "ets_additive_seasonal": "Per-store ETS (weekly)"}
    for k, v in bb["baselines"].items():
        o = v["results"]["overall"]["views"]["all_folds"]
        vo = bv["baselines"][k]["results"]["overall"]["views"]["validation"]["wape"]
        params = ", ".join(f"{a}={b}" for a, b in v["params"].items())
        add(f"| {names[k]} | {params} | {o['rmspe']['value']:.3f} | {ci(o['wape'])} | {o['mase']['value']:.3f} | {o['bias']['value']:+.3f} | {vo['value']:.3f} |")
    add("\nThe promo-aware weekday mean was the best baseline in backtest and validation. Details: `evals/results/baselines_backtest.md`.\n")

    add("## Global LightGBM\n")
    sc = mb["selected_config"]
    add(f"One direct multi-horizon model: one row per (store, weekly cutoff, target day), horizon 1-42 as a feature, 45 features (calendar, holidays, "
        f"planned promo flags, Promo2, store attributes, history at the cutoff), target log1p(Sales). Selected on backtest WAPE from a 4-config grid: "
        f"`num_leaves={sc['num_leaves']}`, `min_child_samples={sc['min_child_samples']}` (grid WAPE range "
        f"{min(c['mean_wape'] for c in grid['configs']):.4f}-{max(c['mean_wape'] for c in grid['configs']):.4f}).\n")
    add("| Window | System | RMSPE | WAPE | MASE | Bias |\n|---|---|---|---|---|---|")
    for wl, res, view in (("Backtest (8 folds)", mb["variants"], "all_folds"), ("VALIDATION", mv["variants"], "validation")):
        for n, lbl in (("full", "Global LightGBM"), ("baseline", "Promo-aware weekday mean (K=12)")):
            o = res[n]["overall"]["views"][view]
            add(f"| {wl} | {lbl} | {ci(o['rmspe'])} | {ci(o['wape'])} | {ci(o['mase'])} | {ci(o['bias'])} |")
    c = mb["comparison"]["full_vs_baseline"]
    add(f"\nPaired WAPE difference, model − baseline: backtest {diff(c['all_folds']['wape'])} (folds 2-5, the Jul-Dec 2014 gap period: "
        f"{diff(c['folds_2_5']['wape'])}; other folds: {diff(c['other_folds']['wape'])}); VALIDATION "
        f"{diff(mv['comparison']['full_vs_baseline']['wape'])}.\n")
    add("**Ablations** (backtest, paired WAPE difference ablation − full; positive = the removed part helps):\n")
    add("| Ablation | ΔWAPE [95% CI] |\n|---|---|")
    for k, lbl in (("no_history", "No history features"), ("no_promo", "No promo features"), ("no_holiday", "No holiday features"),
                   ("horizon_fixed_1", "Horizon feature fixed to 1")):
        add(f"| {lbl} | {diff(mb['comparison']['ablations_vs_full'][k]['all_folds']['wape'])} |")
    add("")

    add("## Test result (evaluated once)\n")
    add(f"Forecast from cutoff {rec['cutoff']} for {rec['window'][0]}..{rec['window'][1]}, frozen model trained on data through {rec['cutoff']}.\n")
    add("| System | RMSPE | WAPE | MASE | Bias |\n|---|---|---|---|---|")
    for n, lbl in (("full", "Global LightGBM"), ("baseline", "Promo-aware weekday mean (K=12)"), ("snaive14", "Seasonal naive 14")):
        o = ft["variants"][n]["overall"]["views"]["test"]
        add(f"| {lbl} | {ci(o['rmspe'])} | {ci(o['wape'])} | {ci(o['mase'])} | {ci(o['bias'])} |")
    fc = ft["comparison"]
    add(f"\nPaired WAPE differences: model − baseline {diff(fc['full_minus_baseline']['wape'])}; model − seasonal naive 14 "
        f"{diff(fc['full_minus_snaive14']['wape'])}; baseline − seasonal naive 14 {diff(fc['baseline_minus_snaive14']['wape'])}.\n")
    hz = ft["variants"]["full"]["horizon"]["views"]["test"]
    add("Model WAPE by horizon on TEST: " + ", ".join(f"{k} days {hz[k]['wape']['value']:.3f}" for k in hz) + ". "
        "Full breakdowns (horizon, promo, store type, day of week): [`evals/results/final_test.md`](evals/results/final_test.md).\n")
    add("![Error by horizon](docs/images/test_error_by_horizon.png)\n")
    add("![Across windows](docs/images/validation_vs_test.png)\n")

    add("## Prediction intervals (80%)\n")
    add("Quantile models (q10, q90) with the same features. Calibration: split-conformal factors per horizon bucket, fitted on backtest folds only "
        "and applied unchanged to VALIDATION and TEST.\n")
    add("| Set | Coverage, uncalibrated | Coverage, calibrated | Relative width, uncalibrated | Relative width, calibrated |\n|---|---|---|---|---|")
    for lbl, u, k in (("Backtest (calibrated = in-sample)", "backtest_uncalibrated", "backtest_calibrated_in_sample"),
                      ("VALIDATION", "validation_uncalibrated", "validation_calibrated"), ("TEST", "test_uncalibrated", "test_calibrated")):
        add(f"| {lbl} | {ci(ivc[u]['overall']['coverage'])} | {ci(ivc[k]['overall']['coverage'])} | "
            f"{ivc[u]['overall']['rel_width']['value']:.3f} | {ivc[k]['overall']['rel_width']['value']:.3f} |")
    tc = ivc["test_calibrated"]["overall"]
    add(f"\nOn TEST the calibrated misses are uneven: {tc['share_below']['value']:.3f} of actuals fall below the interval and "
        f"{tc['share_above']['value']:.3f} above it.\n")
    add("![Interval coverage](docs/images/interval_coverage.png)\n")

    add("## Promotion analysis — association, not causation\n")
    r = promo["regression"]["specs"]
    add("Rossmann chose when promotions ran (they alternate by week), so these are adjusted associations. They say nothing about profit, "
        "cannibalisation or what would happen under a different promotion schedule.\n")
    for k, lbl in (("A_store_dow_week", "store + weekday + week-of-year fixed effects"), ("B_plus_holidays", "+ holiday indicators"),
                   ("C_store_x_dow", "store × weekday fixed effects")):
        p = r[k]["promo"]
        add(f"- Within-store regression ({lbl}): promo days have {p['pct']:+.1f}% higher sales [{p['pct_lo']:+.1f}%, {p['pct_hi']:+.1f}%] "
            f"(store-clustered CI, {r[k]['n']:,} Mon-Fri open days of TRAIN).")
    d = r["D_plus_neighbouring_promo_flags"]
    add(f"- Around promo days (timing pattern, not an effect): the day after a promo day {d['promo_prev_day']['pct']:+.1f}%, "
        f"the day before {d['promo_next_day']['pct']:+.1f}%.")
    mbm = promo["model_based"]["neighbours_as_observed"]["overall"]
    add(f"- In the global model, setting Promo to 1 vs 0 changes predicted sales by a factor of {mbm['geometric_mean_ratio']:.3f} "
        f"[{mbm['ci_lo']:.3f}, {mbm['ci_hi']:.3f}] (store-level spread p10-p90: {mbm['store_ratio_p10']:.3f}-{mbm['store_ratio_p90']:.3f}).")
    add("- Details and per-store-type numbers: [`evals/results/promo_analysis.md`](evals/results/promo_analysis.md).\n")

    add("## Limitations\n")
    trees = [x for c in grid["configs"] for x in c["best_iteration_per_fold"].values()] + \
            [x for k, v in mb["best_iteration_per_fold"].items() if k != "full" for x in v] + \
            [x for v in ivb["quantile_models"]["trees_per_fold"].values() for x in v] + list(mv["trees"].values())
    capped = sum(1 for x in trees if x >= 1500)
    add(f"- **Single test window, single retailer.** TEST is one 42-day summer window ({rec['window'][0]}..{rec['window'][1]}) from one cutoff; it does "
        "not establish performance in other seasons (e.g. Christmas), years, horizons or retailers.")
    add(f"- **20% training-row sample** (fixed seed) for compute reasons, and a **1,500-tree cap**: {capped} of {len(trees)} early-stopped fits "
        f"reached it (the final q10 model uses {mv['trees']['q10']} trees).")
    add(f"- **Back-transform bias:** forecasts are expm1 of a log-scale prediction (roughly a median). Bias is reported everywhere; a smearing "
        f"correction was tested as a secondary variant and over-forecast on VALIDATION, so it was not adopted.")
    add("- **Open flag assumed known** for the forecast days: closed days are forecast as 0 and excluded, so unplanned closures are not evaluated.")
    add(f"- **Data gap:** {cov['max_stores_missing_on_one_date']} stores have no rows from July to December 2014; why is not in the data.")
    add("- Bootstrap CIs capture store sampling only; fold-to-fold variation in the backtest is much larger.\n")

    add("## App screenshots\n")
    add("Local Streamlit app (`streamlit run app/app.py`); it reads only the aggregate files in `evals/results/`. The store-level viewer tab "
        "needs the Kaggle data on your own machine and is deliberately not pictured.\n")
    for fname, caption in SCREENSHOTS:
        if not (ROOT / "docs" / "images" / fname).exists():
            raise FileNotFoundError(fname)
        add(f"![{caption}](docs/images/{fname})\n*{caption}*\n")

    add("## Reproduce\n")
    add("```bash\npython3 -m venv .venv && .venv/bin/pip install -r requirements.txt\nexport ROSSMANN_RAW_DIR=/path/to/rossmann-raw\n"
        "python scripts/prepare_data.py && python scripts/make_windows.py && python scripts/audit_data.py\n"
        "python scripts/run_baselines.py --stage backtest && python scripts/run_baselines.py --stage validation\n"
        "for s in features grid ablations quantiles analysis report validation; do python scripts/run_model.py --stage $s; done\n"
        "python scripts/final_test.py --stage calibrate && python scripts/final_test.py --stage train\n"
        "python scripts/final_test.py --stage test        # one-shot; refuses a second run\n"
        "python scripts/make_figures.py && python scripts/make_readme.py\npython -m pytest\nstreamlit run app/app.py\n```\n")
    add("If ROS 2 is sourced, prefix commands with `env -u PYTHONPATH`. Scripts cap numerical threads at 1, LightGBM at 2 threads, and run a "
        "memory watchdog that exits below 1 GB of available RAM.\n")

    add("## AI assistance\n")
    add("This project was built with Claude Code assisting on code and drafting. The author specified the protocol (windows, leakage rules, "
        "metrics, one-shot test) and reviewed every result.\n")
    return "\n".join(L)


def main():
    text = render()
    if "--check" in sys.argv:
        sys.exit(0 if (ROOT / "README.md").read_text() == text else 1)
    (ROOT / "README.md").write_text(text)


if __name__ == "__main__":
    main()
